use poseidon_core::domain::*;
use ts_rs::{Config, TS};

fn declarations() -> String {
    let config = Config::default();
    let declarations = [
        GitInstallation::decl(&config),
        StashSelection::decl(&config),
        StashEntry::decl(&config),
        StashList::decl(&config),
        StashListResponse::decl(&config),
        StashAction::decl(&config),
        StashPlan::decl(&config),
        StashPlanResponse::decl(&config),
        StashDetailsResponse::decl(&config),
        WorktreeKind::decl(&config),
        WorktreeAvailability::decl(&config),
        Worktree::decl(&config),
        WorktreeList::decl(&config),
        WorktreeListResponse::decl(&config),
        WorktreeFilters::decl(&config),
        WorktreeStatus::decl(&config),
        WorktreeStatusResponse::decl(&config),
        BranchAction::decl(&config),
        BranchPlan::decl(&config),
        BranchPlanResponse::decl(&config),
        BranchOutcome::decl(&config),
        BranchChange::decl(&config),
        BranchChangeResponse::decl(&config),
        CommitPlan::decl(&config),
        CommitPlanResponse::decl(&config),
        CommitOutcome::decl(&config),
        CommitCreation::decl(&config),
        CreateCommitResponse::decl(&config),
        ErrorCode::decl(&config),
        AppError::decl(&config),
        Head::decl(&config),
        Commit::decl(&config),
        CommitDetail::decl(&config),
        Branch::decl(&config),
        CommitRef::decl(&config),
        GraphSegment::decl(&config),
        GraphRow::decl(&config),
        HistoryPage::decl(&config),
        HistoryResponse::decl(&config),
        FileChange::decl(&config),
        WorkingStatus::decl(&config),
        RepositorySnapshot::decl(&config),
        SnapshotResponse::decl(&config),
        DetailResponse::decl(&config),
        ChangeKind::decl(&config),
        DiffBase::decl(&config),
        ChangedFile::decl(&config),
        CommitFiles::decl(&config),
        CommitFilesResponse::decl(&config),
        WorkingArea::decl(&config),
        WorkingChanges::decl(&config),
        WorkingChangesResponse::decl(&config),
        IndexChange::decl(&config),
        IndexChangeResponse::decl(&config),
        DiffTarget::decl(&config),
        DiffLineKind::decl(&config),
        DiffLine::decl(&config),
        DiffContent::decl(&config),
        FileDiff::decl(&config),
        FileDiffResponse::decl(&config),
    ];
    let mut result = "// Generated by `npm run bindings`. Do not edit by hand.\n".to_owned();
    for declaration in declarations {
        result.push_str("export ");
        result.push_str(
            &declaration
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n"),
        );
        result.push('\n');
    }
    result
}

fn main() -> std::result::Result<(), Box<dyn std::error::Error>> {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/lib/ipc/bindings.ts");
    let content = declarations();
    if std::env::args().any(|s| s == "--check") {
        if std::fs::read_to_string(&path)? != content {
            return Err("IPC bindings differ. Run npm run bindings.".into());
        }
    } else {
        std::fs::create_dir_all(path.parent().ok_or("missing parent")?)?;
        std::fs::write(path, content)?;
    }
    Ok(())
}
